#!/usr/bin/env python3
"""Prepare local Astra integration without editing the user's global Codex settings."""

from __future__ import annotations

import argparse
import json
import shutil
import sys
import tomllib
from pathlib import Path


def prepare(
    project: Path,
    output: Path,
    home: Path,
    *,
    project_skill: bool = False,
    project_mcp: bool = False,
    force: bool = False,
) -> dict:
    project, output, home = project.resolve(), output.resolve(), home.resolve()
    python = project / ".venv" / "bin" / "python"
    if not python.is_file():
        raise ValueError(f"Missing runtime: {python}. Run uv sync --python 3.12 first.")
    # TOML accepts Unicode scalar values directly, including emoji in project paths.
    command = json.dumps(str(python), ensure_ascii=False)
    cache = json.dumps(str(home), ensure_ascii=False)
    config = (
        "# Generated by VidLens; merge this section into your Codex configuration.\n"
        "[mcp_servers.vidlens]\n"
        f"command = {command}\n"
        'args = ["-m", "vidlens", "mcp"]\n'
        "tool_timeout_sec = 1500\n"
        "\n[mcp_servers.vidlens.env]\n"
        f"VIDLENS_HOME = {cache}\n"
        'PYTHONUNBUFFERED = "1"\n'
    )
    expected = tomllib.loads(config)["mcp_servers"]["vidlens"]
    launch = {key: expected[key] for key in ("command", "args", "env")}
    mcp_json = {"mcpServers": {"vidlens": launch}}
    output.mkdir(parents=True, exist_ok=True)
    (output / "codex.toml").write_text(config, encoding="utf-8")
    (output / "mcp.json").write_text(json.dumps(mcp_json, indent=2) + "\n", encoding="utf-8")
    result = {
        "codex_config_fragment": str(output / "codex.toml"),
        "mcp_config": str(output / "mcp.json"),
        "runtime": str(python),
        "cache": str(home),
        "global_settings_changed": False,
    }
    mcp_path = project / ".codex" / "config.toml"
    append_mcp = False
    if project_mcp:
        existing = mcp_path.read_text(encoding="utf-8") if mcp_path.exists() else ""
        current = tomllib.loads(existing).get("mcp_servers", {}).get("vidlens")
        append_mcp = current is None
        if current is not None and (
            not isinstance(current, dict)
            or current.get("command") != launch["command"]
            or current.get("args") != launch["args"]
            or not isinstance(current.get("env"), dict)
            or current["env"].get("VIDLENS_HOME") != str(home)
        ):
            raise ValueError(
                f"Existing VidLens MCP settings differ in {mcp_path}. Review the generated fragment."
            )
        result["project_mcp"] = str(mcp_path)
    if project_skill:
        source = project / "skills" / "read-video"
        destination = project / ".agents" / "skills" / "read-video"
        if not (source / "SKILL.md").is_file():
            raise ValueError(f"Missing source skill at {source}. Run this installer from the VidLens checkout.")
        paths = [
            path for path in source.rglob("*") if path.is_file() and "__pycache__" not in path.parts
        ]
        for path in paths:
            target = destination / path.relative_to(source)
            if target.exists() and target.read_bytes() != path.read_bytes() and not force:
                raise ValueError(
                    f"Existing skill differs: {target}. Review it, then use --force to update."
                )
        for path in paths:
            target = destination / path.relative_to(source)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(path, target)
        (destination / "runtime.json").write_text(
            json.dumps({"project_root": str(project), "home": str(home)}, indent=2) + "\n",
            encoding="utf-8",
        )
        result["project_skill"] = str(destination)
        result["skill_activation"] = "Start a new chat in this project to discover the skill."
    # Apply project settings only after checking and installing the requested skill.
    if append_mcp:
        mcp_path.parent.mkdir(parents=True, exist_ok=True)
        prefix = existing + "\n" if existing else ""
        mcp_path.write_text(prefix + config, encoding="utf-8")
    if project_mcp:
        result["next_step"] = "Reconnect VidLens or start a new chat in this project."
    else:
        result["next_step"] = "Review the generated codex.toml fragment and merge it to enable MCP."
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    project = Path(__file__).resolve().parents[1]
    parser.add_argument("--output", type=Path, default=project / "integrations" / "astra")
    parser.add_argument("--home", type=Path, default=project / ".vidlens")
    parser.add_argument(
        "--project-skill",
        action="store_true",
        help="Install skill in this project's .agents/skills",
    )
    parser.add_argument(
        "--project-mcp",
        action="store_true",
        help="Add VidLens to this project's .codex/config.toml without replacing other settings",
    )
    parser.add_argument(
        "--force", action="store_true", help="Replace a modified project skill after review"
    )
    args = parser.parse_args()
    try:
        result = prepare(
            project,
            args.output,
            args.home,
            project_skill=args.project_skill,
            project_mcp=args.project_mcp,
            force=args.force,
        )
        print(json.dumps(result, ensure_ascii=False, indent=2))
        return 0
    except (OSError, ValueError) as exc:
        print(json.dumps({"error": str(exc)}, ensure_ascii=False), file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
